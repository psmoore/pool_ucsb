#!/usr/bin/env python3
"""
Generate the preview pages.

Each page's own content lives in src/<slug>.html, whose first line is an HTML comment carrying
its <title> and meta description. The chrome around it (the unofficial ribbon, the
Department of Recreation masthead, the strip linking every page in this preview, the footer)
is the same on every page, so it lives here. Calendars are written as {{cal:<key>}} and filled
from EMBEDS. Run `python3 build.py` and commit the HTML it writes.
"""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = "https://recreation.ucsb.edu"
REGISTER = "https://register.recreation.ucsb.edu"

# Pool Relay public calendars (share tokens).
EMBEDS = {
    "week":    ("r5IiLBDG7TrDooOHy2iZnK", "Both pools, the whole week"),
    "lanes":   ("DOjT3FkMWt5sZKPj9b3lKr", "Today, lane by lane"),
    "masters": ("ZcPBpxGtb9kCjeX9kuYTAY", "Gaucho Masters Swim week"),
    "fitness": ("ijYLaEPaHUyqtoApYmfx6x", "Water Fitness week"),
    "scuba":   ("hKnk03AZDvKWOeGDDf0tcF", "SCUBA pool sessions"),
}

# Every page in this preview: (file, label, the page it replicates)
PAGES = [
    ("index.html",         "Aquatics & Safety",   "/aquatics-safety"),
    ("masters.html",       "Gaucho Masters Swim", "/aquatics-safety#collapse-9002"),
    ("water-fitness.html", "Water Fitness",       "/aquatics-safety#collapse-8624"),
    ("scuba.html",         "SCUBA",               "/adventure-programs/scuba"),
]
ORIGIN = {f: SITE + path for f, _, path in PAGES}
EXT = 'target="_blank" rel="noopener noreferrer"'


def cal(m):
    token, label = EMBEDS[m.group(1)]
    return (f'<div class="frame"><iframe src="https://www.poolrelay.com/embed/{token}" '
            f'title="UCSB Rec Cen Pools: {label}" loading="lazy"></iframe></div>')


def shell(slug, title, description, body):
    origin = ORIGIN[slug]
    on = ' class="on" aria-current="page"'
    strip = "\n".join(f'    <a href="{f}"{on if f == slug else ""}>{label}</a>' for f, label, _ in PAGES)
    return f"""<!doctype html>
<!--
  UNOFFICIAL PREVIEW. Not a UC Santa Barbara website.
  A replica of {origin}
  Generated by build.py from src/{slug} &mdash; edit those, not this file.
-->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex, nofollow">
<title>{title}</title>
<meta name="description" content="{description}">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Nunito+Sans:wght@400;600;700;800&display=swap">
<link rel="stylesheet" href="site.css">
</head>
<body>

<div class="preview-note">
  <b>Unofficial preview.</b> Not a UC Santa Barbara page &mdash; a mock-up of
  <a href="{origin}" {EXT}>recreation.ucsb.edu</a>
  with its pool calendar shown as a live Pool Relay calendar. Built by
  <a href="https://www.poolrelay.com" {EXT}>Pool Relay</a>.
</div>

<div class="topbar">
  <div class="in">
    <span>University of California, Santa Barbara</span>
    <a class="register" href="{REGISTER}" {EXT}>Register Here</a>
  </div>
</div>

<header class="site">
  <div class="in">
    <a class="wordmark" href="index.html"><small>UC <b>SANTA BARBARA</b></small>Department of Recreation</a>
    <nav class="site">
      <a href="{SITE}/about/overview" {EXT}>About</a>
      <a href="{SITE}/adventure-programs" {EXT}>Adventure Programs</a>
      <a class="here" href="index.html">Aquatics</a>
      <a href="{SITE}/classes-events" {EXT}>Classes</a>
      <a href="{SITE}/facilities-services" {EXT}>Facilities &amp; Services</a>
      <a href="{SITE}/sport-programs" {EXT}>Sport Programs</a>
      <a href="{SITE}/youth-programs" {EXT}>Youth Programs</a>
    </nav>
  </div>
  <nav class="strip" aria-label="Pages in this preview">
{strip}
  </nav>
</header>

{body.strip()}

<footer class="site">
  <div class="in">
    <div>
      <b>UCSB Recreation Center</b>
      516 Ocean Road, Santa Barbara, CA 93106<br>
      Pool Office: (805) 893-7213
    </div>
    <div>
      <b>Aquatics &amp; Safety</b>
      Nancy Clayton, Assistant Director, Aquatics &amp; Safety<br>
      Rick Van Hoorn, Aquatics Coordinator
    </div>
  </div>
  <p class="fine">This page is an unofficial preview built to demonstrate an embedded
    <a href="https://www.poolrelay.com" {EXT}>Pool Relay</a> calendar. It is not operated by or
    affiliated with UC Santa Barbara or its Department of Recreation. For official schedules see
    <a href="{SITE}/aquatics-safety" {EXT}>recreation.ucsb.edu</a>.</p>
</footer>

</body>
</html>
"""


def main():
    for slug, _, _ in PAGES:
        src = open(os.path.join(HERE, "src", slug), encoding="utf-8").read()
        m = re.match(r"\s*<!--\s*title:\s*(.*?)\n\s*description:\s*(.*?)\s*-->\s*", src, re.S)
        if not m:
            raise SystemExit(f"src/{slug}: first line must be the title/description comment")
        body = re.sub(r"\{\{cal:(\w+)\}\}", cal, src[m.end():])
        open(os.path.join(HERE, slug), "w", encoding="utf-8").write(shell(slug, m.group(1).strip(), m.group(2).strip(), body))
        print("wrote", slug)


if __name__ == "__main__":
    main()
